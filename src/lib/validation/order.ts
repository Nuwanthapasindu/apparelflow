// Single source of truth for order input rules. Imported by the Zod schema on the server AND by
// the order modal, so client and server cannot drift. Keep this file free of server-only imports.
import { z } from "zod";

export const TARGET_QTY_MIN = 1;
export const TARGET_QTY_MAX = 100_000;
export const RECIPE_ID_MAX = 64;
export const FABRIC_ROLL_ID_MIN = 3;
export const FABRIC_ROLL_ID_MAX = 40;
/** Up to 6 integer digits (no leading zeros) and at most 2 decimals: max 999999.99. */
export const FABRIC_YDS_PATTERN = /^(0|[1-9]\d{0,5})(\.\d{1,2})?$/;
export const FABRIC_ROLL_ID_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;
/** Text a person may type for a piece count: digits only, no sign, no decimals, no exponent. */
const WHOLE_NUMBER_TEXT = /^\d{1,6}$/;

/** Order ids are UUIDs generated by Prisma. Anything else cannot exist, so it is a 404 without a query. */
export const ORDER_ID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
export const isOrderId = (id: string) => ORDER_ID_PATTERN.test(id);

export const MESSAGES = {
  recipe: "Choose a recipe",
  recipeUnknown: "That recipe does not exist",
  targetQty: `Enter a whole number from ${TARGET_QTY_MIN} to ${TARGET_QTY_MAX.toLocaleString("en-US")}`,
  fabricRollId: `Use ${FABRIC_ROLL_ID_MIN} to ${FABRIC_ROLL_ID_MAX} letters, digits, dots, dashes or underscores, starting with a letter or digit`,
  fabricYds: "Enter yards greater than 0, with up to 2 decimals (for example 12.5)",
} as const;

/** Error message for a recipe id, or null when valid. Existence is checked against the database. */
export function checkRecipeId(value: unknown): string | null {
  return typeof value === "string" && value.length >= 1 && value.length <= RECIPE_ID_MAX ? null : MESSAGES.recipe;
}

/** The server takes a JSON number: strings such as "50" are rejected. */
export function checkTargetQty(value: unknown): string | null {
  if (typeof value !== "number" || !Number.isInteger(value)) return MESSAGES.targetQty;
  return value >= TARGET_QTY_MIN && value <= TARGET_QTY_MAX ? null : MESSAGES.targetQty;
}

/** Typed text from the form: digits only, then the same range rule as the server. */
export function parseTargetQtyText(text: string): { value: number } | { error: string } {
  if (!WHOLE_NUMBER_TEXT.test(text)) return { error: MESSAGES.targetQty };
  const value = Number(text);
  const error = checkTargetQty(value);
  return error ? { error } : { value };
}

/** Trims, then checks. The server schema trims first as well. */
export function checkFabricRollId(value: unknown): string | null {
  if (typeof value !== "string") return MESSAGES.fabricRollId;
  const id = value.trim();
  const long = id.length >= FABRIC_ROLL_ID_MIN && id.length <= FABRIC_ROLL_ID_MAX;
  return long && FABRIC_ROLL_ID_PATTERN.test(id) ? null : MESSAGES.fabricRollId;
}

/**
 * Yards arrive as a string or a JSON number. Numbers are checked through String(n); raw input is
 * never passed to Number() or parseFloat(). Must match the pattern and be greater than zero.
 */
export function checkFabricYds(value: unknown): string | null {
  const text = typeof value === "number" ? (Number.isFinite(value) ? String(value) : "") : value;
  if (typeof text !== "string" || !FABRIC_YDS_PATTERN.test(text)) return MESSAGES.fabricYds;
  return /[1-9]/.test(text) ? null : MESSAGES.fabricYds; // "0", "0.0", "0.00" are not > 0
}

/** "12" -> "12.00", "12.5" -> "12.50". Pure string work, no floating point. */
export function normalizeFabricYds(text: string): string {
  const [whole, fraction = ""] = text.split(".");
  return `${whole}.${fraction.padEnd(2, "0")}`;
}

const refine =
  <T>(check: (value: T) => string | null) =>
  (value: T, ctx: { addIssue: (issue: { code: "custom"; message: string }) => void }) => {
    const message = check(value);
    if (message) ctx.addIssue({ code: "custom", message });
  };

/** POST /api/orders body. Strict: status, createdBy, currentAttempt, orderNo or anything else is a 400. */
export const createOrderSchema = z.strictObject({
  recipeId: z.string({ error: MESSAGES.recipe }).superRefine(refine(checkRecipeId)),
  targetQty: z.number({ error: MESSAGES.targetQty }).superRefine(refine(checkTargetQty)),
  fabricRollId: z.string({ error: MESSAGES.fabricRollId }).trim().superRefine(refine(checkFabricRollId)),
  actualFabricYds: z
    .union([z.string(), z.number()], { error: MESSAGES.fabricYds })
    .superRefine(refine(checkFabricYds))
    .transform((v) => normalizeFabricYds(String(v))),
});

export type CreateOrderInput = z.output<typeof createOrderSchema>;
